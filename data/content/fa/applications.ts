import type { ContentBlock, ContentDocument } from "@/content/models/content-document";

function app(
  slug: string,
  title: string,
  seoTitle: string,
  seoDescription: string,
  description: string,
  primaryKeyword: string,
  secondaryKeywords: readonly string[],
  overview: string,
  bullets: readonly string[],
  relatedProducts: readonly string[],
  relatedArticles: readonly string[] = [],
  curatedLinks: readonly { label: string; path: string; hint?: string }[] = [],
): ContentDocument {
  const sections: ContentBlock[] = [
    { type: "paragraph", text: overview },
    { type: "heading", level: 2, text: "ملاحظات طراحی" },
    { type: "list", items: bullets },
  ];

  if (curatedLinks.length > 0) {
    sections.push({
      type: "internal-links",
      title: "محصول و راهنمای مرتبط",
      links: curatedLinks,
    });
  }

  return {
    id: `application-${slug}`,
    slug,
    path: `/applications/${slug}`,
    locale: "fa",
    kind: "application",
    title,
    seoTitle,
    seoDescription,
    description,
    primaryKeyword,
    secondaryKeywords,
    status: "published",
    evidenceStatus: "candidate",
    verificationStatus: "legacy-claim",
    lastReviewed: "2026-09-05",
    breadcrumbs: [
      { label: "خانه", path: "/" },
      { label: "کاربردها", path: "/applications" },
      { label: title, path: `/applications/${slug}` },
    ],
    sections,
    related: { products: relatedProducts, articles: relatedArticles },
  };
}

