export function getLegacyMedia(id: string): LegacyMediaRecord | undefined {
  return legacyMedia.find((item) => item.id === id);
}

export function mediaByGrade(grade: MediaGrade): LegacyMediaRecord[] {
  return legacyMedia.filter((item) => item.visualQuality === grade);
}

export function displayableStill(id: string): LegacyMediaRecord | undefined {
  const record = getLegacyMedia(id);
  if (!record) {
    return undefined;
  }
  if (record.format === "mp4" || record.format === "pdf") {
    return undefined;
  }
  if (record.visualQuality === "REJECT") {
    return undefined;
  }
  if (record.websiteRole === "DO_NOT_USE") {
    return undefined;
  }
  if (!record.width || !record.height) {
    return undefined;
  }
  return record;
}

export function descriptiveAlt(record: LegacyMediaRecord): string {
  if (record.websiteRole === "DO_NOT_USE") {
    return "";
  }
  return record.subject;
}

