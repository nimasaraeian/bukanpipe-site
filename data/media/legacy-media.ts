function gcd(a: number, b: number): number {
  return b === 0 ? a : gcd(b, a % b);
}

function ratio(width: number | null, height: number | null): string | null {
  if (!width || !height) {
    return null;
  }
  const divisor = gcd(width, height);
  return `${width / divisor}:${height / divisor}`;
}

type Draft = {
  wpId: number;
  file: string;
  path: string;
  w?: number | null;
  h?: number | null;
  bytes?: number | null;
  format: MediaFormat;
  page: string;
  subject: string;
  category: MediaCategory;
  authenticity?: AuthenticityStatus;
  grade: MediaGrade;
  role: WebsiteRole;
  crop: CropSuitability;
  alt?: string;
  proposed?: string | null;
  notes: string;
  publicAccess?: PublicMediaAccess;
};

function entry(draft: Draft): LegacyMediaRecord {
  const width = draft.w ?? null;
  const height = draft.h ?? null;
  return {
    id: `wp-${draft.wpId}`,
    wpId: draft.wpId,
    sourceUrl: `${WP}/${draft.path}`,
    originalFilename: draft.file,
    width,
    height,
    aspectRatio: ratio(width, height),
    format: draft.format,
    filesizeBytes: draft.bytes ?? null,
    sourcePage: draft.page,
    subject: draft.subject,
    category: draft.category,
    authenticity: draft.authenticity ?? "LEGACY_WP_LIBRARY",
    visualQuality: draft.grade,
    websiteRole: draft.role,
    cropSuitability: draft.crop,
    legacyAlt: draft.alt ?? "",
    proposedFilename: draft.proposed ?? null,
    notes: draft.notes,
    publicAccess: draft.publicAccess,
  };
}

